package orm

import (
	"encoding/json"
	"fmt"
	"math"
	"reflect"
	"strconv"
	"strings"
	"time"

	"github.com/goharbor/harbor/src/lib/q"
)

// operandKind is the kind of value a column accepts as the operand of a filter
type operandKind int

const (
	// kindAny means the operand isn't checked, it is handed to the database as is
	kindAny operandKind = iota
	kindInt
	kindFloat
	kindBool
	kindTime
	kindJSON
)

func (k operandKind) String() string {
	switch k {
	case kindInt:
		return "integer"
	case kindFloat:
		return "number"
	case kindBool:
		return "boolean"
	case kindTime:
		return "timestamp"
	case kindJSON:
		return "JSON"
	}
	return "value"
}

// the layouts accepted for a timestamp operand that isn't converted to time.Time by the query parser
var timeLayouts = []string{
	"2006-01-02",
	"2006-01-02 15:04:05",
	time.RFC3339,
	"2006-01-02 15:04:05Z07:00",
}

// parseOperandKind returns the kind of operand accepted by the model field
func parseOperandKind(field reflect.StructField) operandKind {
	for item := range strings.SplitSeq(field.Tag.Get("orm"), ";") {
		if item == "type(json)" || item == "type(jsonb)" {
			return kindJSON
		}
	}
	t := field.Type
	if t.Kind() == reflect.Pointer {
		t = t.Elem()
	}
	if t == reflect.TypeFor[time.Time]() {
		return kindTime
	}
	switch t.Kind() {
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64:
		return kindInt
	case reflect.Float32, reflect.Float64:
		return kindFloat
	case reflect.Bool:
		return kindBool
	}
	return kindAny
}

// validateOperand checks that the operand of a filter can be converted by the database to the type of the column
func validateOperand(kind operandKind, operand any) error {
	switch v := operand.(type) {
	case time.Time:
		if kind == kindTime || kind == kindAny {
			return nil
		}
	case int64:
		switch kind {
		case kindAny, kindInt, kindFloat, kindJSON:
			return nil
		case kindBool:
			if v == 0 || v == 1 {
				return nil
			}
		}
	case string:
		var ok bool
		switch kind {
		case kindAny:
			ok = true
		case kindInt:
			_, err := strconv.ParseInt(v, 10, 64)
			ok = err == nil
		case kindFloat:
			f, err := strconv.ParseFloat(v, 64)
			ok = err == nil && !math.IsNaN(f) && !math.IsInf(f, 0)
		case kindBool:
			_, err := strconv.ParseBool(v)
			ok = err == nil
		case kindTime:
			for _, layout := range timeLayouts {
				if _, err := time.Parse(layout, v); err == nil {
					ok = true
					break
				}
			}
		case kindJSON:
			ok = json.Valid([]byte(v))
		}
		if ok {
			return nil
		}
	default:
		// the operand is the type that isn't generated by the query parser, leave it to the caller
		return nil
	}
	return fmt.Errorf("%v is not a valid %s", operand, kind)
}

// validateOperands validates the operand(s) carried by the value of a filter: a single value, a range or a list
func validateOperands(kind operandKind, value any) error {
	if kind == kindAny {
		return nil
	}
	var operands []any
	switch v := value.(type) {
	case *q.Range:
		if v == nil {
			return nil
		}
		operands = []any{v.Min, v.Max}
	case *q.OrList:
		if v == nil {
			return nil
		}
		operands = v.Values
	case *q.AndList, *q.FuzzyMatchValue:
		return nil
	default:
		operands = []any{value}
	}
	for _, operand := range operands {
		if operand == nil {
			continue
		}
		if err := validateOperand(kind, operand); err != nil {
			return err
		}
	}
	return nil
}
